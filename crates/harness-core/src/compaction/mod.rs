/// Key of the marker object in a variant's `meta`.
pub const META_KEY: &str = "compaction";
/// Version of the [`Marker`] layout.
pub const MARKER_VERSION: u32 = 1;

/// Same texts as the Playground's tool loop (`agentLoop.ts`), so a request built here is the
/// request the Playground sends.
pub const DENIED_TEXT: &str = "User denied this tool call.";
pub const CANCELLED_TEXT: &str = "Tool call was cancelled before it ran.";

/// Template tokens a chat message costs beyond its text (role header, separators).
pub const MESSAGE_OVERHEAD: u64 = 5;

/// Share of the context the kept (verbatim) turns may take after a compaction; older kept
/// turns are summarized too when they are larger.
pub const KEEP_CAP_PERCENT: u64 = 40;

/// An automatic compaction must summarize at least this share of the context: it rewrites
/// the prompt prefix (llama-server re-evaluates the prompt from the first changed token), so
/// it should happen rarely and in large chunks, never for one small turn.
pub const AUTO_MIN_PERCENT: u64 = 10;

/// How the summary is produced.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[cfg_attr(feature = "openapi", schema(as = CompactionStrategy))]
#[serde(rename_all = "snake_case")]
pub enum Strategy {
    /// One short free-form paragraph ("summarize this conversation"); the baseline.
    Brief,
    /// Sectioned summary that copies concrete facts verbatim (goals, facts, decisions, open
    /// items), in as few passes as the context allows. The default (best fact retention per
    /// token in the comparison, see ARCHITECTURE.md).
    #[default]
    Structured,
    /// The structured prompt over small chunks (a quarter of the context each), the summary
    /// carried from chunk to chunk.
    Incremental,
}

impl Strategy {
    pub fn as_str(self) -> &'static str {
        match self {
            Strategy::Brief => "brief",
            Strategy::Structured => "structured",
            Strategy::Incremental => "incremental",
        }
    }
}

/// What started a compaction.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[cfg_attr(feature = "openapi", schema(as = CompactionTrigger))]
#[serde(rename_all = "snake_case")]
pub enum TriggerKind {
    #[default]
    Manual,
    Auto,
}

/// When automatic compaction fires.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(tag = "mode", rename_all = "snake_case")]
pub enum Threshold {
    /// A share of the model's (per-slot) context, in percent.
    Percent { percent: f64 },
    /// A fixed token count (never above 95 % of the context).
    Tokens { tokens: u64 },
}

impl Default for Threshold {
    fn default() -> Self {
        Threshold::Percent { percent: 80.0 }
    }
}

impl Threshold {
    /// Token count from which compaction triggers for a context of `n_ctx` tokens.
    pub fn limit(&self, n_ctx: u64) -> u64 {
        let cap = n_ctx.saturating_mul(95) / 100;
        match *self {
            Threshold::Percent { percent } => {
                let p = if percent.is_finite() {
                    percent.clamp(10.0, 98.0)
                } else {
                    80.0
                };
                (n_ctx as f64 * p / 100.0).floor() as u64
            }
            Threshold::Tokens { tokens } if n_ctx > 0 => tokens.max(1).min(cap),
            Threshold::Tokens { tokens } => tokens.max(1),
        }
    }
}

/// True when the next request (`used` tokens of the conversation so far plus `incoming`
/// tokens of the new message) reaches the threshold.
pub fn should_compact(used: u64, incoming: u64, n_ctx: u64, threshold: Threshold) -> bool {
    n_ctx > 0 && used.saturating_add(incoming) >= threshold.limit(n_ctx)
}

/// The compaction marker stored in `meta.compaction` of the marker message's variant.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[cfg_attr(feature = "openapi", schema(as = CompactionMarker))]
pub struct Marker {
    pub version: u32,
    /// Last message the summary covers; the request continues after it.
    pub boundary_id: String,
    /// Conversation messages the summary covers (including what an earlier summary covered).
    pub covered: u32,
    /// Turns summarized by this compaction.
    pub turns: u32,
    /// Turns kept verbatim after the boundary when it was made.
    pub kept_turns: u32,
    pub trigger: TriggerKind,
    pub strategy: Strategy,
    #[serde(default)]
    pub instruction: Option<String>,
    /// Model that wrote the summary.
    #[serde(default)]
    pub model: Option<String>,
    /// Prompt tokens of the conversation before / after (system, summary, kept turns).
    pub tokens_before: u64,
    pub tokens_after: u64,
    pub summary_tokens: u64,
    /// Tool results shortened before summarizing.
    #[serde(default)]
    pub tool_results_cleared: u32,
    /// Token counts came from the server's tokenizer (else estimated).
    #[serde(default)]
    pub exact_tokens: bool,
    /// Earlier marker whose summary was folded into this one.
    #[serde(default)]
    pub previous_id: Option<String>,
    /// Undone by the user: the request ignores it (and auto-compaction pauses on this path).
    #[serde(default)]
    pub undone: bool,
    /// Made while an answer was still running (between two tool rounds), see [`plan_mid_turn`].
    #[serde(default)]
    pub mid_turn: bool,
    /// The user message of the running turn: it lies before the boundary but is still sent
    /// verbatim right after the summary (a request must keep the question it answers).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pinned_id: Option<String>,
    pub created_at: i64,
}

/// The marker in a variant's `meta`, if it has one.
pub fn marker_of(meta: Option<&Value>) -> Option<Marker> {
    let v = meta?.get(META_KEY)?;
    serde_json::from_value(v.clone()).ok()
}

/// `meta` with a compaction marker's message ids (`boundary_id`, `previous_id`) mapped
/// through `map` (copying a conversation gives its messages new ids). Other metadata is
/// returned unchanged; an id `map` does not know is kept.
pub fn remap_meta(meta: Option<&Value>, map: impl Fn(&str) -> Option<String>) -> Option<Value> {
    let mut meta = meta?.clone();
    if let Some(m) = meta.get_mut(META_KEY).and_then(Value::as_object_mut) {
        for key in ["boundary_id", "previous_id", "pinned_id"] {
            let mapped = m.get(key).and_then(Value::as_str).and_then(&map);
            if let Some(new) = mapped {
                m.insert(key.into(), Value::String(new));
            }
        }
    }
    Some(meta)
}

/// The marker of a path message (a `system` message with `meta.compaction`).
pub fn message_marker(m: &PathMessage) -> Option<Marker> {
    if m.role != "system" {
        return None;
    }
    marker_of(m.variant.meta.as_ref())
}

/// The compaction a request built from `path` applies.
#[derive(Debug, Clone, PartialEq)]
pub struct Active {
    pub marker_index: usize,
    pub boundary_index: usize,
    /// Path index of the marker's pinned user message (before the boundary).
    pub pinned_index: Option<usize>,
    pub marker: Marker,
    pub summary: String,
}

/// The newest marker on `path` that is not undone and whose boundary is on the path
/// before it.
pub fn active_compaction(path: &[PathMessage]) -> Option<Active> {
    for (i, m) in path.iter().enumerate().rev() {
        let Some(marker) = message_marker(m) else {
            continue;
        };
        if marker.undone {
            continue;
        }
        if let Some(b) = path[..i].iter().position(|p| p.id == marker.boundary_id) {
            let pinned_index = marker
                .pinned_id
                .as_deref()
                .and_then(|id| path[..b].iter().position(|p| p.id == id));
            return Some(Active {
                marker_index: i,
                boundary_index: b,
                pinned_index,
                summary: m.variant.content.clone(),
                marker,
            });
        }
    }
    None
}

/// The newest marker on the path was undone: automatic compaction waits until the user
/// re-applies it or compacts by hand (else it would immediately redo what was undone).
pub fn auto_paused(path: &[PathMessage]) -> bool {
    path.iter()
        .rev()
        .find_map(message_marker)
        .is_some_and(|m| m.undone)
}

/// The summary as part of the system message.
pub fn summary_block(summary: &str) -> String {
    format!(
        "<conversation_summary>\nThe earlier part of this conversation was compacted to save \
         context. Summary of those messages (treat it as what was said; the newest messages \
         follow verbatim):\n\n{}\n</conversation_summary>",
        summary.trim()
    )
}

/// A conversation message (user / assistant) as opposed to markers and other system rows.
pub(crate) fn is_chat(m: &PathMessage) -> bool {
    m.role == "user" || m.role == "assistant"
}

#[derive(Debug, Clone, Deserialize)]
pub(crate) struct ToolCall {
    #[serde(default)]
    pub id: String,
    #[serde(default)]
    pub name: String,
    #[serde(default)]
    pub arguments: String,
    #[serde(default)]
    pub status: String,
    #[serde(default)]
    pub result: Option<String>,
}

fn parse_calls(v: Option<&Value>) -> Vec<ToolCall> {
    match v {
        Some(Value::Array(a)) => a
            .iter()
            .filter_map(|c| serde_json::from_value::<ToolCall>(c.clone()).ok())
            .filter(|c| !c.id.is_empty())
            .collect(),
        _ => Vec::new(),
    }
}

/// One model request's answer: its text and the tool calls it made (with their results).
#[derive(Debug, Clone)]
pub(crate) struct Round {
    pub content: String,
    pub calls: Vec<ToolCall>,
}

/// Key under a variant's `meta` that holds the *earlier* rounds of its answer. The split view
/// runs a tool loop per side and stores one answer per side in a single message variant: the
/// variant itself is the last round, `meta.rounds` the ones before it (oldest first).
pub const ROUNDS_KEY: &str = "rounds";

/// The rounds of an assistant message in order: the stored earlier rounds, then its own.
pub(crate) fn rounds(m: &PathMessage) -> Vec<Round> {
    let mut out: Vec<Round> = m
        .variant
        .meta
        .as_ref()
        .and_then(|meta| meta.get(ROUNDS_KEY))
        .and_then(Value::as_array)
        .map(|a| {
            a.iter()
                .map(|r| Round {
                    content: r
                        .get("content")
                        .and_then(Value::as_str)
                        .unwrap_or_default()
                        .to_string(),
                    calls: parse_calls(r.get("tool_calls")),
                })
                .collect()
        })
        .unwrap_or_default();
    out.push(Round {
        content: m.variant.content.clone(),
        calls: parse_calls(m.variant.tool_calls.as_ref()),
    });
    out
}

pub(crate) fn tool_message_content(c: &ToolCall) -> &str {
    if c.status == "denied" {
        return DENIED_TEXT;
    }
    c.result.as_deref().unwrap_or(CANCELLED_TEXT)
}

/// OpenAI-format messages of one stored message (tool rounds: the assistant message with
/// `tool_calls` plus one `tool` message per call). Empty for markers and failed answers.
fn api_messages(m: &PathMessage, out: &mut Vec<Value>) {
    match m.role.as_str() {
        "user" => out.push(json!({ "role": "user", "content": m.variant.content })),
        "assistant" => {
            for r in rounds(m) {
                if !r.calls.is_empty() {
                    out.push(json!({
                        "role": "assistant",
                        "content": r.content,
                        "tool_calls": r.calls.iter().map(|c| json!({
                            "id": c.id,
                            "type": "function",
                            "function": { "name": c.name, "arguments": c.arguments },
                        })).collect::<Vec<_>>(),
                    }));
                    for c in &r.calls {
                        out.push(json!({
                            "role": "tool",
                            "tool_call_id": c.id,
                            "content": tool_message_content(c),
                        }));
                    }
                } else if !r.content.is_empty() {
                    out.push(json!({ "role": "assistant", "content": r.content }));
                }
            }
        }
        _ => {}
    }
}

/// The chat request's messages for `path`, honouring the active compaction (the
/// Playground's `buildApiMessages` does the same in TypeScript).
pub fn request_messages(path: &[PathMessage], system_prompt: &str) -> Vec<Value> {
    let active = active_compaction(path);
    let mut system = system_prompt.trim().to_string();
    if let Some(a) = &active {
        if !system.is_empty() {
            system.push_str("\n\n");
        }
        system.push_str(&summary_block(&a.summary));
    }
    let mut out = Vec::new();
    if !system.is_empty() {
        out.push(json!({ "role": "system", "content": system }));
    }
    let start = active.as_ref().map_or(0, |a| a.boundary_index + 1);
    // A compaction made between two tool rounds keeps the running turn's question verbatim.
    if let Some(p) = active.as_ref().and_then(|a| a.pinned_index) {
        api_messages(&path[p], &mut out);
    }
    for m in &path[start..] {
        api_messages(m, &mut out);
    }
    out
}

/// The text of a message as the model sees it (content, tool calls and results), used to
/// count its tokens.
pub(crate) fn message_text(m: &PathMessage) -> String {
    let mut s = String::new();
    for r in rounds(m) {
        if !s.is_empty() {
            s.push('\n');
        }
        s.push_str(&r.content);
        for c in &r.calls {
            s.push('\n');
            s.push_str(&c.name);
            s.push(' ');
            s.push_str(&c.arguments);
            s.push('\n');
            s.push_str(tool_message_content(c));
        }
    }
    s
}

/// Groups the conversation messages of `path[from..]` into turns (indexes into `path`): a
/// user message and every assistant message after it. Markers are skipped.
pub fn turns(path: &[PathMessage], from: usize) -> Vec<Vec<usize>> {
    let mut out: Vec<Vec<usize>> = Vec::new();
    for (i, m) in path.iter().enumerate().skip(from) {
        if !is_chat(m) {
            continue;
        }
        if m.role == "user" || out.is_empty() {
            out.push(vec![i]);
        } else if let Some(last) = out.last_mut() {
            last.push(i);
        }
    }
    out
}

/// Limits of one compaction plan.
#[derive(Debug, Clone, Copy)]
pub struct PlanOptions {
    /// The chat model's context (per slot), in tokens.
    pub n_ctx: u64,
    /// Newest turns to keep verbatim (fewer when they take more than [`KEEP_CAP_PERCENT`]
    /// of the context; at least one turn is always summarized).
    pub keep_turns: usize,
    /// Smallest token count worth summarizing (automatic compaction; 0 = anything).
    pub min_tokens: u64,
}

/// Which messages a compaction summarizes and which it keeps.
#[derive(Debug, Clone, PartialEq)]
pub struct Plan {
    /// Indexes into the path of the messages to summarize (conversation messages only).
    pub summarize: Vec<usize>,
    /// Indexes of the kept messages (after the boundary).
    pub kept: Vec<usize>,
    /// Index of the last summarized message (the new boundary).
    pub boundary: usize,
    pub summarize_tokens: u64,
    pub kept_tokens: u64,
    pub turns: usize,
    pub kept_turns: usize,
    /// The running turn's user message, kept verbatim although it lies before the boundary
    /// ([`plan_mid_turn`] only) and its token count.
    pub pinned: Option<usize>,
    pub pinned_tokens: u64,
    /// The marker currently applied (its summary is folded into the new one).
    pub previous: Option<Active>,
}

/// Chooses what to summarize. `tokens[i]` is the token count of `path[i]` (0 for markers).
pub fn plan(path: &[PathMessage], tokens: &[u64], opts: &PlanOptions) -> Result<Plan, ErrorKey> {
    let previous = active_compaction(path);
    let start = previous.as_ref().map_or(0, |a| a.boundary_index + 1);
    let turns = turns(path, start);
    if turns.is_empty() {
        return Err(err("compaction.nothing_to_compact"));
    }
    let tok = |idx: &[usize]| -> u64 {
        idx.iter()
            .map(|&i| tokens.get(i).copied().unwrap_or(0))
            .sum()
    };
    let cap = if opts.n_ctx > 0 {
        opts.n_ctx * KEEP_CAP_PERCENT / 100
    } else {
        u64::MAX
    };
    // Always summarize at least one turn; kept turns must leave room for the next answer.
    let mut keep = opts.keep_turns.min(turns.len() - 1);
    while keep > 0 {
        let kept: u64 = turns[turns.len() - keep..].iter().map(|t| tok(t)).sum();
        if kept <= cap {
            break;
        }
        keep -= 1;
    }
    let split = turns.len() - keep;
    let summarize: Vec<usize> = turns[..split].iter().flatten().copied().collect();
    let kept: Vec<usize> = turns[split..].iter().flatten().copied().collect();
    let summarize_tokens = tok(&summarize);
    if summarize_tokens < opts.min_tokens {
        return Err(err("compaction.too_little")
            .num("tokens", summarize_tokens)
            .num("min", opts.min_tokens));
    }
    let boundary = *summarize.last().expect("at least one turn is summarized");
    Ok(Plan {
        kept_tokens: tok(&kept),
        summarize,
        kept,
        boundary,
        summarize_tokens,
        turns: split,
        kept_turns: keep,
        pinned: None,
        pinned_tokens: 0,
        previous,
    })
}

/// Chooses what to summarize while an answer is still running (a long tool loop crossed the
/// threshold between two rounds). The path ends with the running turn: its user message and
/// the assistant rounds so far.
///
/// * Two or more rounds: everything up to the second-to-last round is summarized (older turns
///   and the early rounds of this turn); the last round, whose tool results the model has not
///   seen yet, stays verbatim, and the turn's user message is *pinned* (sent verbatim right
///   after the summary, so the request still starts with the question being answered).
///   Older turns are folded into the summary instead of being kept (`keep_turns` does not
///   apply: this is the emergency case where the running turn alone fills the context).
/// * One round: only earlier turns can be summarized; the running turn is kept whole.
pub fn plan_mid_turn(
    path: &[PathMessage],
    tokens: &[u64],
    opts: &PlanOptions,
) -> Result<Plan, ErrorKey> {
    let previous = active_compaction(path);
    let start = previous.as_ref().map_or(0, |a| a.boundary_index + 1);
    let turns = turns(path, start);
    let Some(current) = turns.last() else {
        return Err(err("compaction.nothing_to_compact"));
    };
    let tok = |idx: &[usize]| -> u64 {
        idx.iter()
            .map(|&i| tokens.get(i).copied().unwrap_or(0))
            .sum()
    };
    let rounds: Vec<usize> = current
        .iter()
        .copied()
        .filter(|&i| path[i].role == "assistant")
        .collect();
    let first_is_user = current.first().is_some_and(|&i| path[i].role == "user");
    let (pinned, boundary, summarize, kept, turn_count) = if rounds.len() >= 2 {
        // The question being answered: the turn's user message, or (the turn was already
        // compacted once) the message the previous marker pinned.
        let pinned = if first_is_user {
            current.first().copied()
        } else {
            previous.as_ref().and_then(|a| a.pinned_index)
        };
        let Some(pinned) = pinned else {
            return Err(err("compaction.nothing_to_compact"));
        };
        let boundary = rounds[rounds.len() - 2];
        let summarize: Vec<usize> = (start..=boundary)
            .filter(|&i| i != pinned && is_chat(&path[i]))
            .collect();
        let kept: Vec<usize> = (boundary + 1..path.len())
            .filter(|&i| is_chat(&path[i]))
            .collect();
        (Some(pinned), boundary, summarize, kept, turns.len())
    } else if first_is_user && turns.len() >= 2 {
        let older = &turns[..turns.len() - 1];
        let summarize: Vec<usize> = older.iter().flatten().copied().collect();
        let boundary = *summarize.last().expect("an older turn exists");
        (None, boundary, summarize, current.clone(), turns.len() - 1)
    } else {
        return Err(err("compaction.nothing_to_compact"));
    };
    let summarize_tokens = tok(&summarize);
    if summarize.is_empty() || summarize_tokens < opts.min_tokens {
        return Err(err("compaction.too_little")
            .num("tokens", summarize_tokens)
            .num("min", opts.min_tokens));
    }
    Ok(Plan {
        kept_tokens: tok(&kept),
        pinned_tokens: pinned.map_or(0, |p| tok(&[p])),
        summarize,
        kept,
        boundary,
        summarize_tokens,
        turns: turn_count,
        kept_turns: 1,
        pinned,
        previous,
    })
}

/// Refuses a compaction whose request would not get smaller (`compaction.no_gain`).
pub fn require_gain(tokens_before: u64, tokens_after: u64) -> Result<(), ErrorKey> {
    if tokens_after >= tokens_before {
        return Err(err("compaction.no_gain")
            .num("before", tokens_before)
            .num("after", tokens_after));
    }
    Ok(())
}

/// Output budget of the summary: the requested size, else 1/8 of the context (256–2048).
pub fn summary_budget(n_ctx: u64, requested: Option<u64>) -> u64 {
    match requested.filter(|&r| r > 0) {
        Some(r) => r.clamp(64, (n_ctx / 3).max(64)),
        None => (n_ctx / 8).clamp(256, 2048),
    }
}

/// Transcript tokens one summarization request may carry: what is left of the context after
/// the summary output, the instructions, the previous summary and a 5 % margin (a quarter of
/// the context at most for [`Strategy::Incremental`]).
pub fn chunk_budget(
    n_ctx: u64,
    summary_max: u64,
    overhead: u64,
    previous_summary: u64,
    strategy: Strategy,
) -> Result<u64, ErrorKey> {
    let avail = n_ctx
        .saturating_sub(summary_max)
        .saturating_sub(overhead)
        .saturating_sub(previous_summary)
        .saturating_sub(n_ctx / 20);
    let avail = match strategy {
        Strategy::Incremental => avail.min(n_ctx / 4),
        _ => avail,
    };
    if avail < 256 {
        return Err(err("compaction.context_too_small").num("n_ctx", n_ctx));
    }
    Ok(avail)
}

/// Splits consecutive entries (their token counts) into chunks of at most `budget` tokens.
/// An entry larger than the budget is a chunk of its own (the caller shortens it).
pub fn chunks(entry_tokens: &[u64], budget: u64) -> Vec<std::ops::Range<usize>> {
    let mut out = Vec::new();
    let mut start = 0;
    let mut sum = 0u64;
    for (i, &t) in entry_tokens.iter().enumerate() {
        if i > start && sum + t > budget {
            out.push(start..i);
            start = i;
            sum = 0;
        }
        sum += t;
    }
    if start < entry_tokens.len() {
        out.push(start..entry_tokens.len());
    }
    out
}

/// Tool results longer than this are shortened in the summarizer's transcript when
/// "clear old tool results" is on.
pub const TOOL_RESULT_KEEP_CHARS: usize = 300;

/// One message as a transcript entry for the summarizer, and how many tool results were
/// shortened.
pub(crate) fn transcript_entry(m: &PathMessage, clear_tool_results: bool) -> (String, u32) {
    let mut cleared = 0;
    let mut s = String::new();
    let content = m.variant.content.trim();
    match m.role.as_str() {
        "user" => s.push_str(&format!("User: {content}")),
        _ => {
            for r in rounds(m) {
                let content = r.content.trim();
                if !content.is_empty() {
                    if !s.is_empty() {
                        s.push('\n');
                    }
                    s.push_str(&format!("Assistant: {content}"));
                }
                for c in r.calls {
                    if !s.is_empty() {
                        s.push('\n');
                    }
                    s.push_str(&format!(
                        "Assistant called tool `{}` with {}",
                        c.name,
                        c.arguments.trim()
                    ));
                    let result = tool_message_content(&c).trim();
                    let shown = if clear_tool_results
                        && result.chars().count() > TOOL_RESULT_KEEP_CHARS
                    {
                        cleared += 1;
                        let head: String = result.chars().take(TOOL_RESULT_KEEP_CHARS).collect();
                        format!(
                            "{head} … [rest of the tool result cleared, {} characters]",
                            result.chars().count() - TOOL_RESULT_KEEP_CHARS
                        )
                    } else {
                        result.to_string()
                    };
                    s.push_str(&format!(
                        "
Tool result ({}): {shown}",
                        c.name
                    ));
                }
            }
            if s.is_empty() {
                s.push_str("Assistant: (no answer)");
            }
        }
    }
    (s, cleared)
}

/// Shortens `text` (counted as `tokens`) to about `budget` tokens, keeping its start and end.
pub(crate) fn shorten(text: &str, tokens: u64, budget: u64) -> String {
    if tokens <= budget || tokens == 0 {
        return text.to_string();
    }
    let chars: Vec<char> = text.chars().collect();
    let keep = ((chars.len() as f64) * (budget as f64 / tokens as f64) * 0.9) as usize;
    let head = keep * 2 / 3;
    let tail = keep - head;
    let mut s: String = chars[..head.min(chars.len())].iter().collect();
    s.push_str(" … [shortened] … ");
    s.extend(chars[chars.len().saturating_sub(tail)..].iter());
    s
}

/// Rough token count when no tokenizer answers (≈ 3 characters per token, on the high side).
pub fn estimate_tokens(text: &str) -> u64 {
    (text.chars().count() as u64).div_ceil(3)
}

/// Removes a reasoning block some models put before the answer.
pub(crate) fn strip_think(s: &str) -> String {
    let mut out = s.to_string();
    while let (Some(a), Some(b)) = (out.find("<think>"), out.find("</think>")) {
        if b < a {
            break;
        }
        out.replace_range(a..b + "</think>".len(), "");
    }
    out.trim().to_string()
}
