//! Context compaction of Playground conversations.
//!
//! A long conversation outgrows the model's context. Compaction replaces its older turns, in
//! the request only, by a model-written summary while the newest turns stay verbatim. Nothing
//! is deleted: the summary is a **marker** in the message tree (`role = system`, the summary
//! as the variant content, [`Marker`] under `meta.compaction`), appended after the last
//! message at the time of compaction. A request built from a path that contains an active
//! marker sends
//!
//! ```text
//! system prompt + <summary block>   ← the marker's summary
//! messages after marker.boundary_id ← kept turns + everything after the marker
//! ```
//!
//! so the original messages stay in `state.db`, the UI shows them (dimmed) with a divider,
//! and *undo* only flags the marker (`undone`), which makes the request use the full history
//! (or the previous marker) again. Branches made before the marker do not contain it. A new
//! compaction on a path that already has one folds the old summary into the new one (rolling
//! summary). Turns are the unit (a user message and every assistant/tool round answering it),
//! so a tool call and its result are never split.
//!
//! The summary is generated by the chat model itself (or another loaded model) through the
//! same OpenAI-compatible endpoint the Playground talks to; tokens are counted with
//! llama-server's `/tokenize` (or `/v1/messages/count_tokens` through the gateway) and
//! estimated only when neither answers. See `docs/en/ARCHITECTURE.md` (Context compaction) for
//! the design notes and the research behind the defaults.

