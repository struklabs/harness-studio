"""Build summary.json and summary.md from the raw JSON files written by run.py."""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
REPO = Path(__file__).resolve().parents[2]
# BENCH_RESULTS: results folder; BENCH_MACHINE / BENCH_MODELS: the setup lines; BENCH_SECOND: name of the "14b"
# slot (another model on a small card); BENCH_LLAMACPP_LABEL: the plain llama.cpp build.
BASE = REPO / "docs" / "benchmarks" / os.environ.get("BENCH_RESULTS", "2026-10-11")
SECOND = os.environ.get("BENCH_SECOND", "14B")
RAW = BASE / "raw"
BACKENDS = ["harness", "harness_prefix", "harness_prefix_textrecovery", "lmstudio", "lmstudio_control", "ollama", "llamacpp", "llamacpp_b11552"]
LABEL = {"harness": os.environ.get("BENCH_HARNESS_LABEL", "Harness Studio (0.1.1 release build)"), "harness_prefix": "Harness Studio - earlier build (before fixes)", "harness_prefix_textrecovery": "Harness Studio - earlier build + text tool-call recovery (opt-in setting)", "lmstudio_control": "LM Studio - control re-run (same day as the re-run Harness rows)", "lmstudio": "LM Studio", "ollama": "Ollama", "llamacpp": os.environ.get("BENCH_LLAMACPP_LABEL", "llama.cpp b11026 (winget)"),
         "llamacpp_b11552": os.environ.get("BENCH_MANAGED_LABEL", "llama.cpp b11552 (Harness engine)")}


def load() -> dict:
    d: dict = {}
    files = [(f, "") for f in sorted(RAW.glob("*__*__*__*.json"))]
    files += [(f, "_prefix") for f in sorted((RAW / "pre-fix").glob("*__*__*__*.json"))]
    for f, suf in files:
        b, mode, model, metric = f.stem.split("__")
        b = b.replace("harness_textrecovery", "harness_prefix_textrecovery") if suf and b == "harness_textrecovery" else b + suf if b == "harness" else b
        d.setdefault(b, {}).setdefault(mode, {}).setdefault(model, {})[metric] = json.loads(f.read_text(encoding="utf-8"))
    return d


def g(d, *path, default=None):
    for p in path:
        if not isinstance(d, dict) or p not in d:
            return default
        d = d[p]
    return d


def f1(x, nd=1):
    return "-" if x is None else f"{x:.{nd}f}"


def eff(info: dict | None, backend: str) -> str:
    """One-line effective settings."""
    if not info:
        return "?"
    if backend.startswith("harness"):
        c, v = info.get("config", {}), info.get("values", {})
        # The launch line is what ran: Harness turns flash attention on for a quantized V cache
        # although the definition leaves it automatic.
        m = re.search(r"(?:--flash-attn|-fa)s+(S+)", info.get("cmdline") or "")
        fa = m.group(1) if m else ("on" if c.get("flash_attn") else "auto")
        return (f"ctx {v.get('n_ctx', c.get('context_size'))}, ngl {v.get('gpu_layers_offloaded')}/{v.get('gpu_layers_total')}, "
                f"FA {fa}, KV {c.get('cache_type_k') or 'f16'}/{c.get('cache_type_v') or 'f16'}, "
                f"slots {v.get('total_slots')}")
    if backend.startswith("lmstudio"):
        ps = (info.get("ps") or [{}])[0]
        rc = info.get("rest_config") or {}
        fa = rc.get("flash_attention")
        return f"ctx {ps.get('contextLength')}, parallel {ps.get('parallel')}, FA {fa}, flags {' '.join(info.get('flags', [])) or 'none'}"
    if backend == "ollama":
        p = info.get("ps") or {}
        frac = f"{100 * p['size_vram'] / p['size']:.0f}% VRAM" if p.get("size") else "?"
        return f"ctx {p.get('context_length')}, {frac}, env {info.get('env') or 'stock'}"
    pr = info.get("props") or {}
    return f"ctx {pr.get('n_ctx')}, slots {pr.get('total_slots')}, args {' '.join(info.get('args', [])[2:])}"


def build(d: dict) -> tuple[dict, str]:
    env = json.loads((RAW / "_env.json").read_text(encoding="utf-8")) if (RAW / "_env.json").exists() else {}
    md: list[str] = []
    P = md.append
    P("# " + os.environ.get("BENCH_TITLE", "Benchmark: Harness Studio vs LM Studio vs Ollama vs llama.cpp (2026-10-11; Harness rows re-run on the release build)") + "\n")
    P("Generated by `bench/compare/summarize.py` from the raw JSON in `raw/`. All numbers are medians of the stated number "
      "of runs on one machine; see Methodology and Caveats at the end.\n")
    P("## Machine and versions\n")
    machine = os.environ.get("BENCH_MACHINE", "Windows 11 Pro, AMD Ryzen 7 9700X (8 cores), 32 GB RAM, AMD Radeon RX 7900 GRE 16 GB (Vulkan)")
    P(f"- {machine}. Python {env.get('python')}, httpx {env.get('httpx')}.")
    gb = env.get("gpu_baseline", {})
    P(f"- GPU memory in use with nothing loaded (desktop compositor etc.): {gb.get('dedicated_mib')} MiB dedicated, {gb.get('shared_mib')} MiB shared.")
    for n, v in (env.get("versions") or {}).items():
        P(f"- {LABEL.get(n, n)}: {v}")
    P("- Models (identical GGUF files for every tool): " + os.environ.get("BENCH_MODELS", "Qwen3-4B-Instruct-2507 Q4_K_M (2.5 GB, 36 layers + output = 37), "
      "Qwen2.5-Coder-14B-Instruct Q4_K_M (9.0 GB, 49 layers).") + "\n")

    def row_setting(mode: str, model: str):
        P("| Tool | Effective settings |\n|---|---|")
        for b in BACKENDS:
            if b in ("harness_prefix_textrecovery",):
                continue
            err = g(d, b, mode, model, "speed", "error")
            if err == "load_failed":
                P(f"| {LABEL[b]} | REFUSED to load: {str(g(d, b, mode, model, 'speed', 'detail'))[-420:]} |")
                continue
            info = g(d, b, mode, model, "speed", "meta", "endpoint_info") or g(d, b, mode, model, "tools", "meta", "endpoint_info")
            if info is not None:
                P(f"| {LABEL[b]} | {eff(info, b)} (load {info.get('load_s')} s) |")
        P("")

    P("## 1. Effective settings (what each tool ended up with)\n")
    P("### out_of_box, 4B\n")
    row_setting("out_of_box", "4b")
    P(f"### out_of_box, {SECOND}\n")
    row_setting("out_of_box", "14b")
    P("### equal, 4B (requested: ctx 32768, full offload, flash attention on, f16 KV, 1 slot)\n")
    row_setting("equal", "4b")

    P(f"### equal, {SECOND} (requested: ctx 32768, full offload, FA on, f16 KV)\n")    
    row_setting("equal", "14b")

    summ: dict = {"env": env, "results": {}}
    for mode in ("out_of_box", "equal"):
        P(f"## 2. Speed ({mode})\n")
        P("500-token prompt, 256 generated tokens, temperature 0, streaming, median of 5 runs after 1 warm-up; "
          "prompt processing from a ~4k-token prompt, median of 3 runs.\n")
        P("| Tool | Model | TTFT 500-tok (s) | Decode tok/s (client) | Decode tok/s (server) | PP tok/s 4k (client) | PP tok/s 4k (server) |\n|---|---|---|---|---|---|---|")
        for model in ("4b", "14b"):
            for b in BACKENDS:
                s = g(d, b, mode, model, "speed", "summary")
                if s is None:
                    e = g(d, b, mode, model, "speed", "error")
                    if e:
                        P(f"| {LABEL[b]} | {model} | {e} | | | | |")
                    continue
                summ["results"].setdefault(b, {}).setdefault(mode, {}).setdefault(model, {})["speed"] = s
                P(f"| {LABEL[b]} | {model} | {f1(s['ttft_500_s'], 3)} | {f1(s['decode_tps'])} | {f1(s['server_decode_tps'])} | "
                  f"{f1(s['pp4k_tps_client'], 0)} | {f1(s['pp4k_tps_server'], 0)} |")
        P("")

    P("## 3. Long-prompt integrity (out_of_box, 4B, ~20k-token prompt, needle at the start)\n")
    P("| Tool | Effective ctx | Reported prompt tokens | Verdict (2 runs) | Error text |\n|---|---|---|---|---|")
    for b in BACKENDS:
        n = g(d, b, "out_of_box", "4b", "needle")
        if not n:
            continue
        summ["results"].setdefault(b, {}).setdefault("out_of_box", {}).setdefault("4b", {})["needle"] = n.get("summary")
        info = g(n, "meta", "endpoint_info")
        errs = [r.get("error", "") for r in n.get("runs", []) if r.get("error")]
        P(f"| {LABEL[b]} | {eff(info, b).split(',')[0]} | {n['summary']['prompt_tokens_reported']} | {n['summary']['verdicts']} | {(errs[0][:120] if errs else '')} |")
    P("")

    P("## 4. Tool-calling reliability (38 cases, temperature 0, one run per case)\n")
    P("Pass = structured `tool_calls` present when expected, correct name, arguments valid JSON and matching the expected values, "
      "and no tool call when none is expected. Categories: single/choose/parallel/none/nested/enum/turkish/many_tools.\n")
    for mode in ("out_of_box", "equal"):
        P(f"### {mode}\n")
        P("| Tool | Model | Pass | % | Text-format calls seen (converted+passed) | Request errors | By category |\n|---|---|---|---|---|---|---|")
        for model in ("4b", "14b"):
            for b in BACKENDS:
                s = g(d, b, mode, model, "tools", "summary")
                if not s:
                    continue
                summ["results"].setdefault(b, {}).setdefault(mode, {}).setdefault(model, {})["tools"] = s
                cats = ", ".join(f"{k} {v}" for k, v in s["by_category"].items())
                P(f"| {LABEL[b]} | {model} | {s['passed']}/{s['total']} | {s['pct']} | {s['text_format_calls']} ({s['text_format_converted_and_passed']}) | {s['request_errors']} | {cats} |")
        P("")
        P("<details><summary>Failure reasons (out_of_box and equal)</summary>\n") if mode == "equal" else None
    # failure reasons
    md.append("")
    P("### Failed cases (reason per tool)\n")
    for model in ("4b", "14b"):
        for mode in ("out_of_box", "equal"):
            for b in BACKENDS:
                t = g(d, b, mode, model, "tools")
                if not t:
                    continue
                fails = [f"{c['id']}:{c['reason'][:40]}" for c in t.get("cases", []) if not c["pass"]]
                if fails:
                    P(f"- {LABEL[b]} / {mode} / {model}: " + "; ".join(fails))
    P("")
    if True:
        P("</details>\n")

    P("## 5. Agent multi-turn / prompt cache (4B, ~8k-token system prompt + 38 tools, median of 3 conversations)\n")
    P("| Tool | Mode | Turn 1 TTFT (cold, s) | Turn 2 TTFT (s) | Turn 3 TTFT (s) | Turn-1 prompt tokens | Turn-2 cached tokens reported | Turn-3 cached tokens reported | Errors |\n|---|---|---|---|---|---|---|---|---|")
    for mode in ("out_of_box", "equal"):
        for b in BACKENDS:
            s = g(d, b, mode, "4b", "agent", "summary")
            if not s:
                continue
            summ["results"].setdefault(b, {}).setdefault(mode, {}).setdefault("4b", {})["agent"] = s
            P(f"| {LABEL[b]} | {mode} | {f1(s['turn1_ttft_s'], 2)} | {f1(s['turn2_ttft_s'], 2)} | {f1(s['turn3_ttft_s'], 2)} | {s['turn1_prompt_tokens']} | {s['turn2_cached_tokens']} | {s['turn3_cached_tokens']} | {len(s['errors'])} |")
    P("")

    P("## 6. Concurrency: 4 simultaneous streams x 256 tokens (4B)\n")
    P("| Tool | Mode | Slots / ctx | Aggregate tok/s | Wall (s) | Median latency (s) | Max latency (s) | Median TTFT (s) | Max TTFT (s) | Errors |\n|---|---|---|---|---|---|---|---|---|---|")
    for mode in ("out_of_box", "equal4"):
        for b in BACKENDS:
            c = g(d, b, mode, "4b", "concurrency")
            if not c:
                continue
            s = c.get("summary")
            if not s:
                P(f"| {LABEL[b]} | {mode} | | {c.get('error') or c.get('detail')} |")
                continue
            summ["results"].setdefault(b, {}).setdefault(mode, {}).setdefault("4b", {})["concurrency"] = s
            info = g(c, "meta", "endpoint_info")
            P(f"| {LABEL[b]} | {mode} | {eff(info, b)} | {f1(s['aggregate_tps'])} | {f1(s['wall_s'])} | {f1(s['latency_median_s'])} | {f1(s['latency_max_s'])} | {f1(s['ttft_median_s'], 2)} | {f1(s['ttft_max_s'], 2)} | {len(s['errors'])} |")
    P("")

    P(f"## 7. Memory safety: {SECOND} with a 65536 context\n")
    P("| Tool | Outcome | Effective settings | Decode tok/s | VRAM dedicated after load (MiB) | Shared-memory growth (MiB) | Spilled? | Notes |\n|---|---|---|---|---|---|---|---|")
    for b in BACKENDS:
        m = g(d, b, "ctx65536", "14b", "memory")
        if not m:
            continue
        summ["results"].setdefault(b, {}).setdefault("ctx65536", {})["14b"] = {k: m.get(k) for k in ("outcome", "decode", "spilled_to_shared_memory", "shared_growth_mib")}
        if m["outcome"] != "loaded":
            P(f"| {LABEL[b]} | {m['outcome']} | | | | | | {str(m.get('error'))[:200]} |")
            continue
        P(f"| {LABEL[b]} | loaded | {eff(m.get('info'), b)} | {f1(g(m, 'decode', 'decode_tps'))} | {g(m, 'gpu_after_load', 'dedicated_mib')} | {m.get('shared_growth_mib')} | {m.get('spilled_to_shared_memory')} | {'; '.join(g(m, 'decode', 'errors', default=[]))[:100]} |")
    P("")

    P(f"## 8. Model switch: 4B loaded, request the {SECOND} through the API (out_of_box)\n")
    P("| Tool | Outcome | TTFT incl. load (s) | Notes |\n|---|---|---|---|")
    for b in BACKENDS:
        m = g(d, b, "out_of_box", "4b-to-14b", "switch")
        if not m:
            continue
        summ["results"].setdefault(b, {}).setdefault("out_of_box", {})["switch"] = m
        note = m.get("reason") or (g(m, "request", "error") or "")
        if "manual_restart_ready_s" in m:
            note += f" (manual restart to ready: {m['manual_restart_ready_s']} s)"
        if b == "lmstudio":
            note += f" JIT active: {g(m, 'info', 'jit_active')}"
        P(f"| {LABEL[b]} | {m['outcome']} | {f1(m.get('ttft_s'), 2)} | {note[:400]} |")
    P("")
    return summ, "\n".join(x for x in md if x is not None)


def main() -> None:
    d = load()
    summ, md = build(d)
    (BASE / "summary.json").write_text(json.dumps(summ, indent=1, ensure_ascii=False), encoding="utf-8")
    meth = BASE / "_methodology.md"
    tail = meth.read_text(encoding="utf-8") if meth.exists() else ""
    (BASE / "summary.md").write_text(md + "\n" + tail, encoding="utf-8")
    print("wrote", BASE / "summary.md")


if __name__ == "__main__":
    main()
